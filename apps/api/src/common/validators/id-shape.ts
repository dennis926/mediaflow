/**
 * UUID 形状校验：任何 8-4-4-4-12 的十六进制串。
 *
 * 为什么不用 class-validator 的 @IsUUID('4')：早期版本用固定 ID 做种子数据
 * （如 22222222-2222-2222-2222-222222222222），它的版本位/variant 位不符合 RFC，
 * 严格校验会把老安装的默认工作区判为非法。新安装已改用标准 v4，
 * 这里保持宽松以兼容历史数据，业务上仍由数据库外键保证有效性。
 */
export const UUID_SHAPE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
